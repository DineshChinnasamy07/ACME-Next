        #region Implementation of IMapProjectsRepository
        public Task<HeadOfficeConnection?> ResolveOffice(string headOfficeCode, CancellationToken cancellationToken)
        {
            string code = (headOfficeCode ?? string.Empty).Trim().ToLowerInvariant();
            if (code.Length == 0)
            {
                return Task.FromResult<HeadOfficeConnection?>(null);
            }

            return _portal.HeadOfficeConnections.AsNoTracking()
                .FirstOrDefaultAsync(office => office.HeadOfficeCode == code, cancellationToken);
        }

        public async Task<ProjectMappingLookupsDto> FetchMappingLookups(HeadOfficeConnection office, CancellationToken cancellationToken)
        {
            await using (MastersDbContext tenant = await OpenTenantAsync(office, cancellationToken))
            {
                List<MasterProject> projects = await tenant.Projects.AsNoTracking()
                    .Where(row => row.DeleteFlag != 1)
                    .OrderBy(row => row.ProjectCode)
                    .ThenBy(row => row.Project)
                    .ToListAsync(cancellationToken);

                // Mapped branch count per project: new mapping rows win over legacy PROJECT_BRANCH rows.
                Dictionary<int, int> newCounts = (await tenant.Set<ProjectBranchMapping>().AsNoTracking()
                        .Select(row => new { row.ProjectId, row.BranchId })
                        .ToListAsync(cancellationToken))
                    .GroupBy(row => row.ProjectId)
                    .ToDictionary(group => group.Key, group => group.Select(row => row.BranchId).Distinct().Count());
                Dictionary<int, int> legacyCounts = (await tenant.ProjectBranches.AsNoTracking()
                        .Select(row => new { row.ProjectId, row.BranchId })
                        .ToListAsync(cancellationToken))
                    .GroupBy(row => row.ProjectId)
                    .ToDictionary(group => group.Key, group => group.Select(row => row.BranchId).Distinct().Count());

                List<MasterBranchOffice> branches = await tenant.BranchOffices.AsNoTracking()
                    .Where(branch => branch.Status == BranchActivated)
                    .OrderBy(branch => branch.BranchOfficeName)
                    .ToListAsync(cancellationToken);

                ProjectMappingLookupsDto lookups = new ProjectMappingLookupsDto();
                foreach (MasterProject project in projects)
                {
                    int count;
                    if (!newCounts.TryGetValue(project.ProjectId, out count))
                    {
                        legacyCounts.TryGetValue(project.ProjectId, out count);
                    }

                    lookups.Projects.Add(new ProjectMappingProjectDto
                    {
                        ProjectId = project.ProjectId,
                        ProjectCode = project.ProjectCode ?? string.Empty,
                        ProjectName = project.Project ?? string.Empty,
                        CreatedOn = project.AccountDate ?? project.DateStarted,
                        Description = project.Description ?? string.Empty,
                        MappedBranches = count
                    });
                }

                lookups.Branches = branches
                    .Select(branch => new ProjectMappingOptionDto { Id = branch.BranchOfficeId, Code = branch.BranchOfficeCode, Name = branch.BranchOfficeName })
                    .ToList();
                lookups.Locations = await tenant.Set<MappingBranchLocation>().AsNoTracking()
                    .OrderBy(row => row.LocationName)
                    .Where(row => row.LocationId == PrimaryLocationId || row.BranchId > 0)
                    .Select(row => new ProjectMappingOptionDto { Id = row.LocationId, Name = row.LocationName, BranchId = row.BranchId })
                    .ToListAsync(cancellationToken);
                lookups.Societies = await tenant.Societies.AsNoTracking()
                    .OrderBy(row => row.SocietyName)
                    .Select(row => new ProjectMappingOptionDto { Id = row.CustomerId, Name = row.SocietyName ?? string.Empty })
                    .ToListAsync(cancellationToken);
                lookups.Categories = await tenant.ProjectCatogories.AsNoTracking()
                    .OrderBy(row => row.ProjectCatogoryName)
                    .Select(row => new ProjectMappingOptionDto { Id = row.ProjectCatogoryId, Name = row.ProjectCatogoryName ?? string.Empty })
                    .ToListAsync(cancellationToken);
                lookups.Divisions = await tenant.Divisions.AsNoTracking()
                    .Where(row => row.Division != null && row.Division != string.Empty)
                    .OrderBy(row => row.DivisionId)
                    .Select(row => new ProjectMappingOptionDto { Id = row.DivisionId, Name = row.Division })
                    .ToListAsync(cancellationToken);
                lookups.Users = await BranchUsers(tenant, branches, cancellationToken);
                return lookups;
            }
        }

        public async Task<ProjectMappingDetailDto?> FillProjectMapping(HeadOfficeConnection office, int projectId, CancellationToken cancellationToken)
        {
            await using (MastersDbContext tenant = await OpenTenantAsync(office, cancellationToken))
            {
                MasterProject? project = await tenant.Projects.AsNoTracking()
                    .FirstOrDefaultAsync(row => row.ProjectId == projectId && row.DeleteFlag != 1, cancellationToken);
                if (project == null)
                {
                    return null;
                }

                HashSet<int> withTransactions = await BranchesWithTransactions(tenant, projectId, cancellationToken);
                ProjectMappingDetailDto detail = new ProjectMappingDetailDto { ProjectId = projectId };

                List<ProjectBranchMapping> rows = await tenant.Set<ProjectBranchMapping>().AsNoTracking()
                    .Where(row => row.ProjectId == projectId)
                    .OrderBy(row => row.ProjectBranchMapId)
                    .ToListAsync(cancellationToken);
                if (rows.Count > 0)
                {
                    detail.IsSaved = true;
                    detail.Rows = rows.Select(row => new ProjectMappingRowDto
                    {
                        BranchId = row.BranchId,
                        LocationId = row.LocationId,
                        SocietyId = row.CustomerId,
                        CategoryId = row.ProjectCategoryId,
                        DivisionId = row.DivisionId,
                        StartDate = row.DateStarted,
                        EndDate = row.DateClosed,
                        UserId = row.UserId,
                        HasTransactions = withTransactions.Contains(row.BranchId)
                    }).ToList();
                    return detail;
                }

                // Not mapped with this screen yet: start from the legacy PROJECT_BRANCH rows and the project's own
                // society / category / division / dates, so existing mappings are shown and can be completed.
                List<ProjectBranch> legacy = await tenant.ProjectBranches.AsNoTracking()
                    .Where(row => row.ProjectId == projectId)
                    .ToListAsync(cancellationToken);
                detail.Rows = legacy
                    .GroupBy(row => row.BranchId)
                    .Select(group => new ProjectMappingRowDto
                    {
                        BranchId = group.Key,
                        LocationId = group.Min(row => row.LocationId),
                        SocietyId = project.CustomerId,
                        CategoryId = project.ProjectCategoryId,
                        DivisionId = project.DivisionId,
                        StartDate = project.DateStarted,
                        EndDate = project.DateClosed,
                        UserId = null,
                        HasTransactions = withTransactions.Contains(group.Key)
                    })
                    .OrderBy(row => row.BranchId)
                    .ToList();
                return detail;
            }
        }

        public async Task<ProjectMappingActionResult> SaveProjectMapping(HeadOfficeConnection office, ProjectMappingSaveRequest request, CancellationToken cancellationToken)
        {
            List<ProjectMappingRowDto> rows = request.Rows ?? new List<ProjectMappingRowDto>();
            if (rows.Count == 0)
            {
                return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_BRANCH_EMPTY));
            }

            // Field checks that need no database.
            HashSet<int> branchSeen = new HashSet<int>();
            for (int i = 0; i < rows.Count; i++)
            {
                ProjectMappingRowDto row = rows[i];
                if (row.BranchId <= 0) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_ROW_BRANCH_EMPTY, RowLabel(i)), i);
                if (!branchSeen.Add(row.BranchId)) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_BRANCH_DUPLICATE, RowLabel(i)), i);
                if (row.LocationId <= 0) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_ROW_LOCATION_EMPTY, RowLabel(i)), i);
                if (row.SocietyId <= 0) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_ROW_SOCIETY_EMPTY, RowLabel(i)), i);
                if (row.CategoryId <= 0) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_ROW_CATEGORY_EMPTY, RowLabel(i)), i);
                if (row.DivisionId <= 0) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_ROW_DIVISION_EMPTY, RowLabel(i)), i);
                DateTime? start = ToDate(row.StartDate);
                DateTime? end = ToDate(row.EndDate);
                if (!start.HasValue) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_ROW_START_EMPTY, RowLabel(i)), i);
                if (end.HasValue && end.Value < start.Value) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_ROW_DATE_ORDER, RowLabel(i)), i);
            }

            try
            {
                await using (MastersDbContext tenant = await OpenTenantAsync(office, cancellationToken))
                {
                    MasterProject? project = await tenant.Projects
                        .FirstOrDefaultAsync(row => row.ProjectId == request.ProjectId && row.DeleteFlag != 1, cancellationToken);
                    if (project == null)
                    {
                        return Fail(MessageRender.GetMessage(MessageCatalog.Master.Project.PROJECT_NOT_FOUND));
                    }

                    // Lookup checks.
                    List<MasterBranchOffice> branches = await tenant.BranchOffices.AsNoTracking().ToListAsync(cancellationToken);
                    Dictionary<int, MasterBranchOffice> branchById = branches.ToDictionary(branch => branch.BranchOfficeId);
                    Dictionary<int, int> locationBranch = await tenant.Set<MappingBranchLocation>().AsNoTracking()
                        .ToDictionaryAsync(row => row.LocationId, row => row.BranchId, cancellationToken);
                    HashSet<int> societies = (await tenant.Societies.AsNoTracking().Select(row => row.CustomerId).ToListAsync(cancellationToken)).ToHashSet();
                    HashSet<int> categories = (await tenant.ProjectCatogories.AsNoTracking().Select(row => row.ProjectCatogoryId).ToListAsync(cancellationToken)).ToHashSet();
                    HashSet<int> divisions = (await tenant.Divisions.AsNoTracking().Select(row => row.DivisionId).ToListAsync(cancellationToken)).ToHashSet();
                    List<ProjectMappingUserOptionDto> users = await BranchUsers(tenant, branches.Where(branch => branch.Status == BranchActivated).ToList(), cancellationToken);
                    HashSet<(int, int)> branchUsers = users.Select(user => (user.BranchId, user.Id)).ToHashSet();

                    for (int i = 0; i < rows.Count; i++)
                    {
                        ProjectMappingRowDto row = rows[i];
                        MasterBranchOffice? branch;
                        if (!branchById.TryGetValue(row.BranchId, out branch)) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_ROW_BRANCH_EMPTY, RowLabel(i)), i);
                        string code = branch.BranchOfficeCode;
                        int locationOwner;
                        if (!locationBranch.TryGetValue(row.LocationId, out locationOwner)) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_ROW_LOCATION_EMPTY, code), i);
                        if (row.LocationId != PrimaryLocationId && locationOwner != row.BranchId) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_LOCATION_INVALID, code), i);
                        if (!societies.Contains(row.SocietyId)) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_ROW_SOCIETY_EMPTY, code), i);
                        if (!categories.Contains(row.CategoryId)) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_ROW_CATEGORY_EMPTY, code), i);
                        if (!divisions.Contains(row.DivisionId)) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_ROW_DIVISION_EMPTY, code), i);
                        bool branchHasUsers = users.Any(user => user.BranchId == row.BranchId);
                        if (row.UserId.HasValue && row.UserId.Value > 0)
                        {
                            if (!branchUsers.Contains((row.BranchId, row.UserId.Value))) return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_USER_INVALID, code), i);
                        }
                        else if (branchHasUsers)
                        {
                            return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_ROW_USER_EMPTY, code), i);
                        }
                    }

                    // A branch with vouchers for this project must stay mapped.
                    HashSet<int> withTransactions = await BranchesWithTransactions(tenant, project.ProjectId, cancellationToken);
                    HashSet<int> mappedNow = await MappedBranches(tenant, project.ProjectId, cancellationToken);
                    foreach (int branchId in mappedNow)
                    {
                        if (withTransactions.Contains(branchId) && !branchSeen.Contains(branchId))
                        {
                            MasterBranchOffice? branch;
                            string code = branchById.TryGetValue(branchId, out branch) ? branch.BranchOfficeCode : branchId.ToString(System.Globalization.CultureInfo.InvariantCulture);
                            return Fail(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_BRANCH_HAS_TRANSACTIONS, code));
                        }
                    }

                    await using (IDbContextTransaction transaction = await tenant.Database.BeginTransactionAsync(cancellationToken))
                    {
                        DateTime now = DateTime.SpecifyKind(DateTime.Now, DateTimeKind.Unspecified);
                        List<ProjectBranchMapping> existing = await tenant.Set<ProjectBranchMapping>()
                            .Where(row => row.ProjectId == project.ProjectId)
                            .ToListAsync(cancellationToken);
                        Dictionary<int, ProjectBranchMapping> existingByBranch = existing.ToDictionary(row => row.BranchId);

                        // Update kept branches, insert new ones, remove unticked ones.
                        foreach (ProjectMappingRowDto row in rows)
                        {
                            ProjectBranchMapping? entity;
                            if (!existingByBranch.TryGetValue(row.BranchId, out entity))
                            {
                                entity = new ProjectBranchMapping { ProjectId = project.ProjectId, BranchId = row.BranchId, CreatedDate = now };
                                tenant.Set<ProjectBranchMapping>().Add(entity);
                            }
                            else
                            {
                                entity.ModifiedDate = now;
                            }

                            entity.LocationId = row.LocationId;
                            entity.CustomerId = row.SocietyId;
                            entity.ProjectCategoryId = row.CategoryId;
                            entity.DivisionId = row.DivisionId;
                            entity.DateStarted = ToDate(row.StartDate)!.Value;
                            entity.DateClosed = ToDate(row.EndDate);
                            entity.UserId = row.UserId.HasValue && row.UserId.Value > 0 ? row.UserId : null;
                        }

                        tenant.Set<ProjectBranchMapping>().RemoveRange(existing.Where(row => !branchSeen.Contains(row.BranchId)));

                        // Project header keeps the first branch row's details so legacy screens and reports still read them.
                        ProjectMappingRowDto first = rows[0];
                        project.CustomerId = first.SocietyId;
                        project.ProjectCategoryId = first.CategoryId;
                        project.DivisionId = first.DivisionId;
                        project.DateStarted = ToDate(rows.Min(row => row.StartDate));
                        project.DateClosed = rows.All(row => ToDate(row.EndDate).HasValue) ? ToDate(rows.Max(row => row.EndDate)) : null;
                        project.ClosedBy = project.DateClosed.HasValue ? 1 : 0;
                        await tenant.SaveChangesAsync(cancellationToken);

                        // Legacy PROJECT_BRANCH: one row per mapped branch with its location.
                        await tenant.Database.ExecuteSqlRawAsync(
                            "DELETE FROM public.project_branch WHERE \"PROJECT_ID\" = {0}", new object[] { project.ProjectId }, cancellationToken);
                        foreach (ProjectMappingRowDto row in rows)
                        {
                            await tenant.Database.ExecuteSqlRawAsync(
                                "INSERT INTO public.project_branch (\"PROJECT_ID\", \"BRANCH_ID\", \"LOCATION_ID\") VALUES ({0}, {1}, {2})",
                                new object[] { project.ProjectId, row.BranchId, row.LocationId }, cancellationToken);
                        }

                        // Legacy PROJECT_USER: the users in charge (PRO_USER_ID has no sequence, so the table is locked
                        // and the next id taken inside this transaction).
                        await tenant.Database.ExecuteSqlRawAsync(
                            "DELETE FROM public.project_user WHERE \"PROJECT_ID\" = {0}", new object[] { project.ProjectId }, cancellationToken);
                        List<int> userIds = rows.Where(row => row.UserId.HasValue && row.UserId.Value > 0).Select(row => row.UserId!.Value).Distinct().ToList();
                        if (userIds.Count > 0)
                        {
                            await tenant.Database.ExecuteSqlRawAsync("LOCK TABLE public.project_user IN EXCLUSIVE MODE", cancellationToken);
                            foreach (int userId in userIds)
                            {
                                await tenant.Database.ExecuteSqlRawAsync(
                                    "INSERT INTO public.project_user (\"PRO_USER_ID\", \"PROJECT_ID\", \"USER_ID\", \"USER_TYPE\") "
                                    + "SELECT COALESCE((SELECT MAX(\"PRO_USER_ID\") FROM public.project_user), 0) + 1, {0}, {1}, "
                                    + "COALESCE((SELECT \"USER_TYPE\" FROM public.user_info WHERE \"USER_ID\" = {1}), 0)",
                                    new object[] { project.ProjectId, userId }, cancellationToken);
                            }
                        }

                        await transaction.CommitAsync(cancellationToken);
                    }

                    return Ok(MessageRender.GetMessage(MessageCatalog.Master.ProjectMapping.PROJECT_MAPPING_SAVED, rows.Count), project.ProjectId);
                }
            }
            catch (Exception ex)
            {
                return Fail(ex.InnerException?.Message ?? ex.Message);
            }
        }
        #endregion
    }
