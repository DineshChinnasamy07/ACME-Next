    public class MapProjectsRepository : IMapProjectsRepository
    {
        // Branch office STATUS 2 = activated.
        private const int BranchActivated = 2;
        private const int UserActive = 1;

        // BRANCH_LOCATION 1 "Primary" (BRANCH_ID 0) is the default location every branch may use; other locations
        // belong to the branch they were created for (Office › Branch Location).
        private const int PrimaryLocationId = 1;

        // PROJECT_BRANCH_MAPPING was added on 26-11-2026. HO databases created before that do not have it, so the
        // first Project Mapping call on each database creates it (IF NOT EXISTS keeps this safe). Runs once per
        // database per API process; same approach as LegalEntityRepository.EnsureStatutorySchema.
        private static readonly HashSet<string> SchemaChecked = new HashSet<string>();
        private static readonly object SchemaLock = new object();

        private const string MappingSchemaSql = @"
CREATE TABLE IF NOT EXISTS public.project_branch_mapping (
    ""PROJECT_BRANCH_MAP_ID"" integer GENERATED BY DEFAULT AS IDENTITY,
    ""PROJECT_ID"" integer NOT NULL,
    ""BRANCH_ID"" integer NOT NULL,
    ""LOCATION_ID"" integer NOT NULL,
    ""CUSTOMERID"" integer NOT NULL,
    ""PROJECT_CATEGORY_ID"" integer NOT NULL,
    ""DIVISION_ID"" integer NOT NULL,
    ""DATE_STARTED"" timestamp without time zone NOT NULL,
    ""DATE_CLOSED"" timestamp without time zone,
    ""USER_ID"" integer,
    ""CREATED_DATE"" timestamp without time zone DEFAULT now(),
    ""MODIFIED_DATE"" timestamp without time zone,
    CONSTRAINT project_branch_mapping_pkey PRIMARY KEY (""PROJECT_BRANCH_MAP_ID""),
    CONSTRAINT project_branch_mapping_project_fk FOREIGN KEY (""PROJECT_ID"") REFERENCES public.master_project (""PROJECT_ID"") ON DELETE CASCADE,
    CONSTRAINT project_branch_mapping_branch_fk FOREIGN KEY (""BRANCH_ID"") REFERENCES public.branch_office (""BRANCH_OFFICE_ID""),
    CONSTRAINT project_branch_mapping_location_fk FOREIGN KEY (""LOCATION_ID"") REFERENCES public.branch_location (""LOCATION_ID""),
    CONSTRAINT project_branch_mapping_society_fk FOREIGN KEY (""CUSTOMERID"") REFERENCES public.master_insti_perference (""CUSTOMERID""),
    CONSTRAINT project_branch_mapping_category_fk FOREIGN KEY (""PROJECT_CATEGORY_ID"") REFERENCES public.master_project_catogory (""PROJECT_CATOGORY_ID""),
    CONSTRAINT project_branch_mapping_division_fk FOREIGN KEY (""DIVISION_ID"") REFERENCES public.master_division (""DIVISION_ID""),
    CONSTRAINT project_branch_mapping_user_fk FOREIGN KEY (""USER_ID"") REFERENCES public.user_info (""USER_ID"")
);
CREATE UNIQUE INDEX IF NOT EXISTS project_branch_mapping_unique_project_branch ON public.project_branch_mapping USING btree (""PROJECT_ID"", ""BRANCH_ID"");";

        private readonly MastersDbContext _portal;
        private readonly IConfiguration _configuration;

        public MapProjectsRepository(MastersDbContext portal, IConfiguration configuration)
        {
            _portal = portal;
            _configuration = configuration;
        }

        #region Helpers
        private static ProjectMappingActionResult Ok(string message, int projectId)
        {
            return new ProjectMappingActionResult { Success = true, Message = message, ProjectId = projectId, RowIndex = -1 };
        }

        private static string RowLabel(int index)
        {
            return "Row " + (index + 1).ToString(System.Globalization.CultureInfo.InvariantCulture);
        }

        private static ProjectMappingActionResult Fail(string message, int rowIndex = -1)
        {
            return new ProjectMappingActionResult { Success = false, Message = message, RowIndex = rowIndex };
        }

        private MastersDbContext OpenTenant(HeadOfficeConnection office)
        {
            string host = (office.HostName ?? string.Empty).Trim();
            string database = (office.DbName ?? string.Empty).Trim();
            string user = (office.UserName ?? string.Empty).Trim();
            if (host.Length == 0 || database.Length == 0 || user.Length == 0)
            {
                throw new InvalidOperationException(MessageRender.GetMessage(MessageCatalog.Office.HeadOfficeDbMissingForBranch));
            }

            int port;
            if (!int.TryParse(_configuration["HeadOfficeTenant:Port"], out port) || port <= 0)
            {
                port = 3308;
            }

            string connectionString = "Host=" + host
                + ";Port=" + port.ToString(System.Globalization.CultureInfo.InvariantCulture)
                + ";Database=" + database
                + ";Username=" + user
                + ";Password=" + (office.Password ?? string.Empty);
            DbContextOptionsBuilder<MastersDbContext> builder = new DbContextOptionsBuilder<MastersDbContext>();
            builder.UseNpgsql(connectionString);
            return new MastersDbContext(builder.Options);
        }

        private async Task<MastersDbContext> OpenTenantAsync(HeadOfficeConnection office, CancellationToken cancellationToken)
        {
            MastersDbContext tenant = OpenTenant(office);
            try
            {
                await EnsureMappingSchema(tenant, cancellationToken);
                return tenant;
            }
            catch
            {
                await tenant.DisposeAsync();
                throw;
            }
        }

        private static async Task EnsureMappingSchema(MastersDbContext tenant, CancellationToken cancellationToken)
        {
            string key = tenant.Database.GetConnectionString() ?? string.Empty;
            lock (SchemaLock)
            {
                if (SchemaChecked.Contains(key))
                {
                    return;
                }
            }

            await tenant.Database.ExecuteSqlRawAsync(MappingSchemaSql, cancellationToken);

            lock (SchemaLock)
            {
                SchemaChecked.Add(key);
            }
        }

        // Plain calendar date for "timestamp without time zone" columns (mapped with that column type, so the value
        // is stored as given and not shifted by the server time zone).
        private static DateTime? ToDate(DateTime? value)
        {
            if (!value.HasValue || value.Value == DateTime.MinValue)
            {
                return null;
            }

            return DateTime.SpecifyKind(value.Value.Date, DateTimeKind.Unspecified);
        }

        private static string FullName(MappingUser user)
        {
            string name = ((user.FirstName ?? string.Empty) + " " + (user.LastName ?? string.Empty)).Trim();
            return name.Length > 0 ? name : user.UserName;
        }

        // Active users of each branch: users created for the branch (USER_INFO.BRANCH_CODE) plus users mapped to it
        // through BRANCH_USER.
        private static async Task<List<ProjectMappingUserOptionDto>> BranchUsers(MastersDbContext tenant, List<MasterBranchOffice> branches, CancellationToken cancellationToken)
        {
            List<MappingUser> users = await tenant.Set<MappingUser>().AsNoTracking()
                .Where(user => user.Status == UserActive)
                .ToListAsync(cancellationToken);
            List<MappingBranchUser> links = await tenant.Set<MappingBranchUser>().AsNoTracking().ToListAsync(cancellationToken);
            Dictionary<int, MappingUser> byId = users.ToDictionary(user => user.UserId);
            Dictionary<string, int> branchByCode = branches
                .GroupBy(branch => (branch.BranchOfficeCode ?? string.Empty).Trim().ToLowerInvariant())
                .ToDictionary(group => group.Key, group => group.First().BranchOfficeId);
            HashSet<int> branchIds = branches.Select(branch => branch.BranchOfficeId).ToHashSet();

            HashSet<(int, int)> seen = new HashSet<(int, int)>();
            List<ProjectMappingUserOptionDto> result = new List<ProjectMappingUserOptionDto>();
            foreach (MappingUser user in users)
            {
                int branchId;
                string code = (user.BranchCode ?? string.Empty).Trim().ToLowerInvariant();
                if (code.Length > 0 && branchByCode.TryGetValue(code, out branchId) && seen.Add((branchId, user.UserId)))
                {
                    result.Add(new ProjectMappingUserOptionDto { Id = user.UserId, BranchId = branchId, Name = FullName(user), UserName = user.UserName });
                }
            }

            foreach (MappingBranchUser link in links)
            {
                MappingUser? user;
                if (branchIds.Contains(link.BranchId) && byId.TryGetValue(link.UserId, out user) && seen.Add((link.BranchId, link.UserId)))
                {
                    result.Add(new ProjectMappingUserOptionDto { Id = user.UserId, BranchId = link.BranchId, Name = FullName(user), UserName = user.UserName });
                }
            }

            return result.OrderBy(user => user.Name).ToList();
        }

        // Branches that already have vouchers for the project: their mapping cannot be removed.
        private static async Task<HashSet<int>> BranchesWithTransactions(MastersDbContext tenant, int projectId, CancellationToken cancellationToken)
        {
            List<int> rows = await tenant.Database
                .SqlQueryRaw<int>(
                    "SELECT DISTINCT \"BRANCH_ID\" AS \"Value\" FROM public.voucher_master_trans WHERE \"PROJECT_ID\" = {0}",
                    projectId)
                .ToListAsync(cancellationToken);
            return rows.ToHashSet();
        }

        // Branches currently mapped to the project (new mapping table, else legacy PROJECT_BRANCH).
        private static async Task<HashSet<int>> MappedBranches(MastersDbContext tenant, int projectId, CancellationToken cancellationToken)
        {
            List<int> mapped = await tenant.Set<ProjectBranchMapping>().AsNoTracking()
                .Where(row => row.ProjectId == projectId)
                .Select(row => row.BranchId)
                .ToListAsync(cancellationToken);
            if (mapped.Count > 0)
            {
                return mapped.ToHashSet();
            }

            return (await tenant.ProjectBranches.AsNoTracking()
                .Where(row => row.ProjectId == projectId)
                .Select(row => row.BranchId)
                .ToListAsync(cancellationToken)).ToHashSet();
        }
