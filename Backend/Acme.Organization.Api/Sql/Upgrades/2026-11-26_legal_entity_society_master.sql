-- =====================================================================================================
-- Upgrade     : Legal Entity - Society master statutory details (26-Nov-2026)
-- Applies to  : every Head Office (tenant) database created from ACPERP_HO_PG.sql before 26-Nov-2026
-- Purpose     : Adds MASTER_INSTI_STATUTORY (1:1 with MASTER_INSTI_PERFERENCE) and MASTER_INSTI_TAN
--               (several TANs per legal entity) and copies the old single TANNO into the TAN list.
-- Notes       : Safe to run more than once. The Masters API also runs this automatically the first time
--               a Legal Entity screen is used on a database (LegalEntityRepository.EnsureStatutorySchema),
--               so running it by hand is only needed when the tenant login may not CREATE tables.
--               Codes: ENTITY_TYPE 1 Society / 2 Trust; *_STATUS 1 Obtained|Registered / 0 Not.
-- =====================================================================================================

CREATE TABLE IF NOT EXISTS public.master_insti_statutory (
    "CUSTOMERID" integer NOT NULL,
    "ENTITY_TYPE" integer,
    "TRUST_DOC_NO" character varying(100) DEFAULT NULL::character varying,
    "BRANCH_INCHARGE" character varying(100) DEFAULT NULL::character varying,
    "PAN_STATUS" integer,
    "PAN_NAME" character varying(100) DEFAULT NULL::character varying,
    "PAN_REG_DATE" timestamp without time zone,
    "DARPAN_STATUS" integer,
    "DARPAN_ID" character varying(30) DEFAULT NULL::character varying,
    "DARPAN_REG_DATE" timestamp without time zone,
    "DARPAN_NAME" character varying(100) DEFAULT NULL::character varying,
    "A12_STATUS" integer,
    "A12_VALID_FROM" timestamp without time zone,
    "A12_VALID_TO" timestamp without time zone,
    "A12_NAME" character varying(100) DEFAULT NULL::character varying,
    "EIGHTYG_STATUS" integer,
    "EIGHTYG_VALID_FROM" timestamp without time zone,
    "EIGHTYG_VALID_TO" timestamp without time zone,
    "EIGHTYG_NAME" character varying(100) DEFAULT NULL::character varying,
    "FCRA_STATUS" integer,
    "FCRA_VALID_FROM" timestamp without time zone,
    "FCRA_VALID_TO" timestamp without time zone,
    CONSTRAINT master_insti_statutory_pkey PRIMARY KEY ("CUSTOMERID"),
    CONSTRAINT master_insti_statutory_customer_fk FOREIGN KEY ("CUSTOMERID")
        REFERENCES public.master_insti_perference ("CUSTOMERID") ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.master_insti_tan (
    "TAN_ID" integer GENERATED BY DEFAULT AS IDENTITY,
    "CUSTOMERID" integer NOT NULL,
    "TAN_NO" character varying(10) NOT NULL,
    "TAN_REG_DATE" timestamp without time zone,
    "TAN_NAME" character varying(100) DEFAULT NULL::character varying,
    CONSTRAINT master_insti_tan_pkey PRIMARY KEY ("TAN_ID"),
    CONSTRAINT master_insti_tan_customer_fk FOREIGN KEY ("CUSTOMERID")
        REFERENCES public.master_insti_perference ("CUSTOMERID") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS master_insti_tan_unique_customer_tan
    ON public.master_insti_tan USING btree ("CUSTOMERID", "TAN_NO");

-- Existing single TAN -> first row of the TAN list (only for legal entities that have no TAN rows yet).
INSERT INTO public.master_insti_tan ("CUSTOMERID", "TAN_NO")
SELECT p."CUSTOMERID", UPPER(TRIM(p."TANNO"))
FROM public.master_insti_perference p
WHERE TRIM(COALESCE(p."TANNO", '')) <> '' AND LENGTH(TRIM(p."TANNO")) <= 10
  AND NOT EXISTS (SELECT 1 FROM public.master_insti_tan t WHERE t."CUSTOMERID" = p."CUSTOMERID");
