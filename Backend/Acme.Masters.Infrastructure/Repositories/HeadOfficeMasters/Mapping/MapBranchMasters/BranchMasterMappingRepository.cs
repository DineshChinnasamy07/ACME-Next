/*  Class Name      : BranchMasterMappingRepository.cs
 *  Purpose         : Generic Head Office -> Branch master mapping on the HO tenant DB. One table
 *                    (public.master_branch_map) records which master records are available to which branch,
 *                    keyed by MASTER_TYPE. The HO mapping screen reads/writes it; a branch login reads the
 *                    master records mapped to its own branch. New master types are added in MasterQuery only.
 *  Author          : Dinesh C
 *  Created on      : 27-Nov-2026
 */
using Acme.Common;
using Acme.Masters.Application.Abstractions.Repositories.HeadOfficeMasters.Mapping.MapBranchMasters;
using Acme.Masters.Application.Dtos.HeadOfficeMasters.Mapping.MapBranchMasters;
using Acme.Masters.Domain.Entities;
using Acme.Masters.Domain.Entities.HeadOfficeMasters.FinanceMasters.FcPurpose;
using Acme.Masters.Domain.Entities.HeadOfficeMasters.FinanceMasters.LedgerGroup;
using Acme.Masters.Domain.Entities.HeadOfficeMasters.FinanceMasters.Project;
using Acme.Masters.Domain.Entities.HeadOfficeMasters.FinanceMasters.ProjectCategory;
using Acme.Masters.Domain.Entities.HeadOfficeMasters.Mapping.MapBranchMasters;
using Acme.Masters.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;

namespace Acme.Masters.Infrastructure.Repositories.HeadOfficeMasters.Mapping.MapBranchMasters
{
    public class BranchMasterMappingRepository : IBranchMasterMappingRepository
    {
        private const int BranchActivated = 2;

        // Master types this engine knows how to list. Adding a master = one case in MasterQuery + one entry here.
        public static readonly IReadOnlyCollection<string> SupportedTypes = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            "ledger", "ledgergroup", "projectcategory", "fcpurpose", "legalentity"
        };

        private static readonly HashSet<string> SchemaChecked = new HashSet<string>();
        private static readonly object SchemaLock = new object();

        private const string MappingSchemaSql = @"
CREATE TABLE IF NOT EXISTS public.master_branch_map (
    ""MASTER_BRANCH_MAP_ID"" integer GENERATED BY DEFAULT AS IDENTITY,
    ""MASTER_TYPE"" varchar(40) NOT NULL,
    ""MASTER_ID"" integer NOT NULL,
    ""BRANCH_ID"" integer NOT NULL,
    ""CREATED_DATE"" timestamp without time zone DEFAULT now(),
    CONSTRAINT master_branch_map_pkey PRIMARY KEY (""MASTER_BRANCH_MAP_ID""),
    CONSTRAINT master_branch_map_branch_fk FOREIGN KEY (""BRANCH_ID"") REFERENCES public.branch_office (""BRANCH_OFFICE_ID"")
);
CREATE UNIQUE INDEX IF NOT EXISTS master_branch_map_unique ON public.master_branch_map USING btree (""MASTER_TYPE"", ""MASTER_ID"", ""BRANCH_ID"");";

        private readonly MastersDbContext _portal;
        private readonly IConfiguration _configuration;

        public BranchMasterMappingRepository(MastersDbContext portal, IConfiguration configuration)
        {
            _portal = portal;
            _configuration = configuration;
        }

        public static bool IsSupported(string? masterType)
        {
            return !string.IsNullOrWhiteSpace(masterType) && SupportedTypes.Contains(masterType.Trim());
        }

        private static string Normalize(string masterType)
        {
            return (masterType ?? string.Empty).Trim().ToLowerInvariant();
        }

        private MastersDbContext OpenTenant(HeadOfficeConnection office)
        {
            string host = (office.HostName ?? string.Empty).Trim();
            string database = (office.DbName ?? string.Empty).Trim();
            string user = (office.UserName ?? string.Empty).Trim();
            if (host.Length == 0 || database.Length == 0 || user.Length == 0)
            {
                throw new InvalidOperationException(MessageRender.GetMessage(MessageCatalog.Office.HeadOfficeDbMissingForBranch));
            }

            int port;
            if (!int.TryParse(_configuration["HeadOfficeTenant:Port"], out port) || port <= 0)
            {
                port = 3308;
            }

            string connectionString = "Host=" + host
                + ";Port=" + port.ToString(System.Globalization.CultureInfo.InvariantCulture)
                + ";Database=" + database
                + ";Username=" + user
                + ";Password=" + (office.Password ?? string.Empty);
            DbContextOptionsBuilder<MastersDbContext> builder = new DbContextOptionsBuilder<MastersDbContext>();
            builder.UseNpgsql(connectionString);
            return new MastersDbContext(builder.Options);
        }

        private async Task<MastersDbContext> OpenTenantAsync(HeadOfficeConnection office, CancellationToken cancellationToken)
        {
            MastersDbContext tenant = OpenTenant(office);
            try
            {
                await EnsureSchema(tenant, cancellationToken);
                return tenant;
            }
            catch
            {
                await tenant.DisposeAsync();
                throw;
            }
        }

        private static async Task EnsureSchema(MastersDbContext tenant, CancellationToken cancellationToken)
        {
            string key = tenant.Database.GetConnectionString() ?? string.Empty;
            lock (SchemaLock)
            {
                if (SchemaChecked.Contains(key))
                {
                    return;
                }
            }

            await tenant.Database.ExecuteSqlRawAsync(MappingSchemaSql, cancellationToken);

            lock (SchemaLock)
            {
                SchemaChecked.Add(key);
            }
        }

        // The one place that knows each master type's table. onlyIds == null = every record (HO screen);
        // otherwise only those ids (branch read, already scoped to the mapped set).
        private static async Task<List<BranchMasterRecordDto>> MasterQuery(MastersDbContext tenant, string masterType, HashSet<int>? onlyIds, CancellationToken cancellationToken)
        {
            switch (masterType)
            {
                case "ledger":
                {
                    IQueryable<MasterLedger> q = tenant.Ledgers.AsNoTracking();
                    if (onlyIds != null) q = q.Where(r => onlyIds.Contains(r.LedgerId));
                    return await q.OrderBy(r => r.LedgerName)
                        .Select(r => new BranchMasterRecordDto { Id = r.LedgerId, Code = r.LedgerCode ?? string.Empty, Name = r.LedgerName })
                        .ToListAsync(cancellationToken);
                }
                case "ledgergroup":
                {
                    IQueryable<MasterLedgerGroup> q = tenant.LedgerGroups.AsNoTracking();
                    if (onlyIds != null) q = q.Where(r => onlyIds.Contains(r.GroupId));
                    return await q.OrderBy(r => r.LedgerGroup)
                        .Select(r => new BranchMasterRecordDto { Id = r.GroupId, Code = r.GroupCode ?? string.Empty, Name = r.LedgerGroup })
                        .ToListAsync(cancellationToken);
                }
                case "projectcategory":
                {
                    IQueryable<MasterProjectCatogory> q = tenant.ProjectCatogories.AsNoTracking();
                    if (onlyIds != null) q = q.Where(r => onlyIds.Contains(r.ProjectCatogoryId));
                    return await q.OrderBy(r => r.ProjectCatogoryName)
                        .Select(r => new BranchMasterRecordDto { Id = r.ProjectCatogoryId, Code = string.Empty, Name = r.ProjectCatogoryName ?? string.Empty })
                        .ToListAsync(cancellationToken);
                }
                case "fcpurpose":
                {
                    IQueryable<MasterContributionHead> q = tenant.ContributionHeads.AsNoTracking();
                    if (onlyIds != null) q = q.Where(r => onlyIds.Contains(r.ContributionId));
                    return await q.OrderBy(r => r.FcPurpose)
                        .Select(r => new BranchMasterRecordDto { Id = r.ContributionId, Code = r.Code ?? string.Empty, Name = r.FcPurpose ?? string.Empty })
                        .ToListAsync(cancellationToken);
                }
                case "legalentity":
                {
                    IQueryable<MasterInstiPerference> q = tenant.Societies.AsNoTracking();
                    if (onlyIds != null) q = q.Where(r => onlyIds.Contains(r.CustomerId));
                    return await q.OrderBy(r => r.SocietyName)
                        .Select(r => new BranchMasterRecordDto { Id = r.CustomerId, Code = r.RegNo ?? string.Empty, Name = r.SocietyName ?? string.Empty })
                        .ToListAsync(cancellationToken);
                }
                default:
                    return new List<BranchMasterRecordDto>();
            }
        }

        public Task<HeadOfficeConnection?> ResolveOffice(string headOfficeCode, CancellationToken cancellationToken)
        {
            string code = (headOfficeCode ?? string.Empty).Trim().ToLowerInvariant();
            if (code.Length == 0)
            {
                return Task.FromResult<HeadOfficeConnection?>(null);
            }

            return _portal.HeadOfficeConnections.AsNoTracking()
                .FirstOrDefaultAsync(office => office.HeadOfficeCode == code, cancellationToken);
        }

        public async Task<IReadOnlyList<BranchMasterBranchDto>> FetchBranches(HeadOfficeConnection office, CancellationToken cancellationToken)
        {
            await using (MastersDbContext tenant = OpenTenant(office))
            {
                return await tenant.BranchOffices.AsNoTracking()
                    .Where(row => row.Status == BranchActivated)
                    .OrderBy(row => row.BranchOfficeName)
                    .Select(row => new BranchMasterBranchDto { Id = row.BranchOfficeId, Name = row.BranchOfficeName })
                    .ToListAsync(cancellationToken);
            }
        }

        public async Task<IReadOnlyList<BranchMasterRecordDto>> FetchRecords(HeadOfficeConnection office, string masterType, CancellationToken cancellationToken)
        {
            string type = Normalize(masterType);
            await using (MastersDbContext tenant = OpenTenant(office))
            {
                return await MasterQuery(tenant, type, null, cancellationToken);
            }
        }

        public async Task<IReadOnlyList<int>> FetchMappedIds(HeadOfficeConnection office, string masterType, int branchId, CancellationToken cancellationToken)
        {
            string type = Normalize(masterType);
            await using (MastersDbContext tenant = await OpenTenantAsync(office, cancellationToken))
            {
                return await tenant.MasterBranchMaps.AsNoTracking()
                    .Where(row => row.MasterType == type && row.BranchId == branchId)
                    .Select(row => row.MasterId)
                    .ToListAsync(cancellationToken);
            }
        }

        public async Task<BranchMasterMappingResult> SaveMapping(HeadOfficeConnection office, string masterType, int branchId, IReadOnlyList<int> masterIds, CancellationToken cancellationToken)
        {
            string type = Normalize(masterType);
            await using (MastersDbContext tenant = await OpenTenantAsync(office, cancellationToken))
            {
                List<MasterBranchMap> existing = await tenant.MasterBranchMaps
                    .Where(row => row.MasterType == type && row.BranchId == branchId)
                    .ToListAsync(cancellationToken);
                if (existing.Count > 0)
                {
                    tenant.MasterBranchMaps.RemoveRange(existing);
                }

                HashSet<int> ids = new HashSet<int>();
                if (masterIds != null)
                {
                    for (int i = 0; i < masterIds.Count; i++)
                    {
                        if (masterIds[i] > 0) ids.Add(masterIds[i]);
                    }
                }

                DateTime now = DateTime.SpecifyKind(DateTime.Now, DateTimeKind.Unspecified);
                foreach (int id in ids)
                {
                    tenant.MasterBranchMaps.Add(new MasterBranchMap
                    {
                        MasterType = type,
                        MasterId = id,
                        BranchId = branchId,
                        CreatedDate = now
                    });
                }

                await tenant.SaveChangesAsync(cancellationToken);
                return new BranchMasterMappingResult
                {
                    Success = true,
                    Message = ids.Count == 0 ? "All records unmapped from this branch." : ids.Count + " record(s) mapped to this branch.",
                    Count = ids.Count
                };
            }
        }

        public async Task<IReadOnlyList<BranchMasterRecordDto>> FetchBranchMasters(HeadOfficeConnection office, string branchCode, string masterType, CancellationToken cancellationToken)
        {
            string type = Normalize(masterType);
            string branch = (branchCode ?? string.Empty).Trim().ToLowerInvariant();
            if (branch.Length == 0)
            {
                return Array.Empty<BranchMasterRecordDto>();
            }

            await using (MastersDbContext tenant = await OpenTenantAsync(office, cancellationToken))
            {
                int branchId = await tenant.BranchOffices.AsNoTracking()
                    .Where(b => (b.BranchOfficeCode ?? string.Empty).ToLower() == branch)
                    .Select(b => b.BranchOfficeId)
                    .FirstOrDefaultAsync(cancellationToken);
                if (branchId <= 0)
                {
                    return Array.Empty<BranchMasterRecordDto>();
                }

                HashSet<int> mappedIds = new HashSet<int>(
                    await tenant.MasterBranchMaps.AsNoTracking()
                        .Where(row => row.MasterType == type && row.BranchId == branchId)
                        .Select(row => row.MasterId)
                        .Distinct()
                        .ToListAsync(cancellationToken));
                if (mappedIds.Count == 0)
                {
                    return Array.Empty<BranchMasterRecordDto>();
                }

                return await MasterQuery(tenant, type, mappedIds, cancellationToken);
            }
        }
    }
}
