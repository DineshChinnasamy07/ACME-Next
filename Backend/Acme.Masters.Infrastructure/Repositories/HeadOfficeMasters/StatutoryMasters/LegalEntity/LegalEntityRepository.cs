        // Legacy association nature ids (Association enum): 0 Cultural .. 3 Religious .. 5 Others.
        private const int AssociationReligious = 3;
        private const int AssociationOthers = 5;
        private const int AssociationMax = 5;

        // Legacy denomination ids (Denomination enum): 1 Hindu .. 6 Others.
        private const int DenominationOthers = 6;

        private static readonly Regex EmailPattern = new Regex(
            @"^[^@\s]+@[^@\s]+\.[^@\s]+$", RegexOptions.Compiled | RegexOptions.CultureInvariant);

        // Society master statutory codes.
        private const int EntitySociety = 1;
        private const int EntityTrust = 2;
        private const int StatusYes = 1;   // Obtained / Registered
        private const int StatusNo = 0;    // Not Obtained / Not Registered

        // Income-tax formats: PAN = 5 letters, 4 digits, 1 letter; TAN = 4 letters, 5 digits, 1 letter.
        private static readonly Regex PanPattern = new Regex(@"^[A-Z]{5}[0-9]{4}[A-Z]$", RegexOptions.Compiled | RegexOptions.CultureInvariant);
        private static readonly Regex TanPattern = new Regex(@"^[A-Z]{4}[0-9]{5}[A-Z]$", RegexOptions.Compiled | RegexOptions.CultureInvariant);

        // MASTER_INSTI_STATUTORY / MASTER_INSTI_TAN were added on 26-11-2026. HO databases created before that
        // do not have them, so the first Legal Entity call on each database creates them (IF NOT EXISTS keeps
        // this safe) and copies the old single TANNO into the TAN list. Runs once per database per API process.
        // Same approach as Auth UserRepository.EnsureGenderColumn; the tenant login must be allowed to CREATE.
        private static readonly HashSet<string> SchemaChecked = new HashSet<string>();
        private static readonly object SchemaLock = new object();

        private const string StatutorySchemaSql = @"
CREATE TABLE IF NOT EXISTS public.master_insti_statutory (
    ""CUSTOMERID"" integer NOT NULL,
    ""ENTITY_TYPE"" integer,
    ""TRUST_DOC_NO"" character varying(100) DEFAULT NULL::character varying,
    ""BRANCH_INCHARGE"" character varying(100) DEFAULT NULL::character varying,
    ""PAN_STATUS"" integer,
    ""PAN_NAME"" character varying(100) DEFAULT NULL::character varying,
    ""PAN_REG_DATE"" timestamp without time zone,
    ""DARPAN_STATUS"" integer,
    ""DARPAN_ID"" character varying(30) DEFAULT NULL::character varying,
    ""DARPAN_REG_DATE"" timestamp without time zone,
    ""DARPAN_NAME"" character varying(100) DEFAULT NULL::character varying,
    ""A12_STATUS"" integer,
    ""A12_VALID_FROM"" timestamp without time zone,
    ""A12_VALID_TO"" timestamp without time zone,
    ""A12_NAME"" character varying(100) DEFAULT NULL::character varying,
    ""EIGHTYG_STATUS"" integer,
    ""EIGHTYG_VALID_FROM"" timestamp without time zone,
    ""EIGHTYG_VALID_TO"" timestamp without time zone,
    ""EIGHTYG_NAME"" character varying(100) DEFAULT NULL::character varying,
    ""FCRA_STATUS"" integer,
    ""FCRA_VALID_FROM"" timestamp without time zone,
    ""FCRA_VALID_TO"" timestamp without time zone,
    CONSTRAINT master_insti_statutory_pkey PRIMARY KEY (""CUSTOMERID""),
    CONSTRAINT master_insti_statutory_customer_fk FOREIGN KEY (""CUSTOMERID"")
        REFERENCES public.master_insti_perference (""CUSTOMERID"") ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS public.master_insti_tan (
    ""TAN_ID"" integer GENERATED BY DEFAULT AS IDENTITY,
    ""CUSTOMERID"" integer NOT NULL,
    ""TAN_NO"" character varying(10) NOT NULL,
    ""TAN_REG_DATE"" timestamp without time zone,
    ""TAN_NAME"" character varying(100) DEFAULT NULL::character varying,
    CONSTRAINT master_insti_tan_pkey PRIMARY KEY (""TAN_ID""),
    CONSTRAINT master_insti_tan_customer_fk FOREIGN KEY (""CUSTOMERID"")
        REFERENCES public.master_insti_perference (""CUSTOMERID"") ON DELETE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS master_insti_tan_unique_customer_tan ON public.master_insti_tan USING btree (""CUSTOMERID"", ""TAN_NO"");
INSERT INTO public.master_insti_tan (""CUSTOMERID"", ""TAN_NO"")
SELECT p.""CUSTOMERID"", UPPER(TRIM(p.""TANNO""))
FROM public.master_insti_perference p
WHERE TRIM(COALESCE(p.""TANNO"", '')) <> '' AND LENGTH(TRIM(p.""TANNO"")) <= 10
  AND NOT EXISTS (SELECT 1 FROM public.master_insti_tan t WHERE t.""CUSTOMERID"" = p.""CUSTOMERID"");";

        private readonly MastersDbContext _portal;
        private readonly IConfiguration _configuration;

        public LegalEntityRepository(MastersDbContext portal, IConfiguration configuration)
        {
            _portal = portal;
            _configuration = configuration;
        }

        private static LegalEntityActionResult Ok(string message, int id)
        {
            return new LegalEntityActionResult { Success = true, Message = message, CustomerId = id };
        }

        private static LegalEntityActionResult Fail(string message)
        {
            return new LegalEntityActionResult { Success = false, Message = message };
        }

        private MastersDbContext OpenTenant(HeadOfficeConnection office)
        {
            string host = (office.HostName ?? string.Empty).Trim();
            string database = (office.DbName ?? string.Empty).Trim();
            string user = (office.UserName ?? string.Empty).Trim();
            if (host.Length == 0 || database.Length == 0 || user.Length == 0)
            {
                throw new InvalidOperationException(MessageRender.GetMessage(MessageCatalog.Office.HeadOfficeDbMissingForBranch));
            }

            int port;
            if (!int.TryParse(_configuration["HeadOfficeTenant:Port"], out port) || port <= 0)
            {
                port = 3308;
            }

            string connectionString = "Host=" + host
                + ";Port=" + port.ToString(System.Globalization.CultureInfo.InvariantCulture)
                + ";Database=" + database
                + ";Username=" + user
                + ";Password=" + (office.Password ?? string.Empty);
            DbContextOptionsBuilder<MastersDbContext> builder = new DbContextOptionsBuilder<MastersDbContext>();
            builder.UseNpgsql(connectionString);
            return new MastersDbContext(builder.Options);
        }

        private async Task<MastersDbContext> OpenTenantAsync(HeadOfficeConnection office, CancellationToken cancellationToken)
        {
            MastersDbContext tenant = OpenTenant(office);
            try
            {
                await EnsureStatutorySchema(tenant, cancellationToken);
                return tenant;
            }
            catch
            {
                await tenant.DisposeAsync();
                throw;
            }
        }

        private static async Task EnsureStatutorySchema(MastersDbContext tenant, CancellationToken cancellationToken)
        {
            string key = tenant.Database.GetConnectionString() ?? string.Empty;
            lock (SchemaLock)
            {
                if (SchemaChecked.Contains(key))
                {
                    return;
                }
            }

            await tenant.Database.ExecuteSqlRawAsync(StatutorySchemaSql, cancellationToken);

            lock (SchemaLock)
            {
                SchemaChecked.Add(key);
            }
        }

        public Task<HeadOfficeConnection?> ResolveOffice(string headOfficeCode, CancellationToken cancellationToken)
        {
            string code = (headOfficeCode ?? string.Empty).Trim().ToLowerInvariant();
            if (code.Length == 0)
            {
                return Task.FromResult<HeadOfficeConnection?>(null);
            }

            return _portal.HeadOfficeConnections.AsNoTracking()
                .FirstOrDefaultAsync(office => office.HeadOfficeCode == code, cancellationToken);
        }

        /// <summary>
        /// Legacy LegalEntitySQL.FetchAll (HO login: no branch filter), ordered by society name.
        /// </summary>
        public async Task<IReadOnlyList<LegalEntityListItemDto>> FetchLegalEntity(HeadOfficeConnection office, CancellationToken cancellationToken)
        {
            await using (MastersDbContext tenant = await OpenTenantAsync(office, cancellationToken))
            {
                List<LegalEntityListItemDto> rows = await tenant.Set<MasterInstiPerference>().AsNoTracking()
                    .OrderBy(row => row.SocietyName)
                    .Select(row => new LegalEntityListItemDto
                    {
                        CustomerId = row.CustomerId,
                        SocietyName = row.SocietyName ?? string.Empty,
                        RegNo = row.RegNo ?? string.Empty,
                        RegDate = row.RegDate,
                        Place = row.Place ?? string.Empty,
                        State = row.State ?? string.Empty,
                        Country = row.Country ?? string.Empty
                    })
                    .ToListAsync(cancellationToken);

                for (int i = 0; i < rows.Count; i++)
                {
                    rows[i].RegDate = ReadDate(rows[i].RegDate);
                }

                return rows;
            }
        }

