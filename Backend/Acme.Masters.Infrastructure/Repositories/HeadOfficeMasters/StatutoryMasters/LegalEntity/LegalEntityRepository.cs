        public async Task<LegalEntityActionResult> SaveLegalEntityDetails(HeadOfficeConnection office, LegalEntitySaveRequest request, CancellationToken cancellationToken)
        {
            string societyName = Clean(request.SocietyName);
            string country = Clean(request.Country);
            string state = Clean(request.State);
            string regNo = Clean(request.RegNo);
            string email = Clean(request.Email);

            // Legacy ValidateUserControl order: society, country, state, reg no, reg date, permission date,
            // association nature (+ others text), denomination when Religious (+ others text).
            if (societyName.Length == 0)
            {
                return Fail(MessageRender.GetMessage(MessageCatalog.Master.ExecutiveMembers.SOCIETY_NAME_EMPTY));
            }

            if (country.Length == 0)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_COUNTRY_EMPTY));
            }

            if (state.Length == 0)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_STATE_EMPTY));
            }

            if (request.EntityType != EntitySociety && request.EntityType != EntityTrust)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_TYPE_EMPTY));
            }

            if (regNo.Length == 0)
            {
                return Fail(MessageRender.GetMessage(MessageCatalog.License.LEGAL_ENTITY_REGNO_EMPTY));
            }

            string trustDocNo = Clean(request.TrustDocNo);
            if (trustDocNo.Length == 0)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_TRUST_DOC_EMPTY));
            }

            if (!request.RegDate.HasValue)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_REG_DATE_EMPTY));
            }

            string branchIncharge = Clean(request.BranchIncharge);
            if (branchIncharge.Length == 0)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_BRANCH_INCHARGE_EMPTY));
            }

            DateTime today = DateTime.Today;
            if (request.RegDate.HasValue && request.RegDate.Value.Date > today)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_REG_DATE_FUTURE));
            }

            if (request.PermissionDate.HasValue && request.PermissionDate.Value.Date > today)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_PERMISSION_DATE_FUTURE));
            }

            List<int> natures = ParseAssociationNature(request.AssociationNature);
            if (natures.Count == 0)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_ASSOCIATION_NATURE_EMPTY));
            }

            bool isOthers = natures.Contains(AssociationOthers);
            bool isReligious = natures.Contains(AssociationReligious);
            string otherAssociation = isOthers ? Clean(request.OtherAssociationNature) : string.Empty;
            if (isOthers && otherAssociation.Length == 0)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_ASSOCIATION_OTHER_EMPTY));
            }

            int denomination = isReligious ? request.Denomination : 0;
            if (isReligious && (denomination < 1 || denomination > DenominationOthers))
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_DENOMINATION_EMPTY));
            }

            string otherDenomination = denomination == DenominationOthers ? Clean(request.OtherDenomination) : string.Empty;
            if (denomination == DenominationOthers && otherDenomination.Length == 0)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_DENOMINATION_OTHER_EMPTY));
            }

            if (email.Length > 0 && !EmailPattern.IsMatch(email))
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_EMAIL_INVALID));
            }

            // PAN: status required; Obtained needs a valid PAN number and the PAN name.
            if (request.PanStatus != StatusYes && request.PanStatus != StatusNo)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_PAN_STATUS_EMPTY));
            }

            bool hasPan = request.PanStatus == StatusYes;
            bool hasDarpan = request.DarpanStatus == StatusYes;
            bool has12A = request.A12Status == StatusYes;
            bool has80G = request.EightyGStatus == StatusYes;
            bool hasFcra = request.FcraStatus == StatusYes;
            string panNo = hasPan ? Clean(request.PanNo).ToUpperInvariant() : string.Empty;
            string panName = hasPan ? Clean(request.PanName) : string.Empty;
            if (hasPan && panNo.Length == 0)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_PAN_NO_EMPTY));
            }

            if (hasPan && !PanPattern.IsMatch(panNo))
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_PAN_NO_INVALID));
            }

            if (hasPan && panName.Length == 0)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_PAN_NAME_EMPTY));
            }

            string? badStatus = CheckStatus("DARPAN", request.DarpanStatus)
                ?? CheckStatus("12A", request.A12Status)
                ?? CheckStatus("80G", request.EightyGStatus)
                ?? CheckStatus("FCRA", request.FcraStatus);
            if (badStatus != null)
            {
                return Fail(badStatus);
            }

            string darpanId = hasDarpan ? Clean(request.DarpanId) : string.Empty;
            string a12No = has12A ? Clean(request.A12No) : string.Empty;
            string eightyGNo = has80G ? Clean(request.EightyGNo) : string.Empty;
            string fcriNo = hasFcra ? Clean(request.FcriNo) : string.Empty;
            string? missingNumber = (hasDarpan && darpanId.Length == 0 ? NumberRequired("DARPAN ID") : null)
                ?? (has12A && a12No.Length == 0 ? NumberRequired("12A No (URN)") : null)
                ?? (has80G && eightyGNo.Length == 0 ? NumberRequired("80G No") : null)
                ?? (hasFcra && fcriNo.Length == 0 ? NumberRequired("FCRA No") : null);
            if (missingNumber != null)
            {
                return Fail(missingNumber);
            }

            string? futureDate = (hasPan ? CheckNotFuture("PAN Reg Date", request.PanRegDate, today) : null)
                ?? (hasDarpan ? CheckNotFuture("DARPAN Registration Date", request.DarpanRegDate, today) : null)
                ?? (has80G ? CheckNotFuture("80G Reg Date", request.EightyGNoRegDate, today) : null)
                ?? (hasFcra ? CheckNotFuture("FCRA Reg Date", request.FcriRegDate, today) : null);
            if (futureDate != null)
            {
                return Fail(futureDate);
            }

            string? badPeriod = (has12A ? CheckValidity("12A", request.A12ValidFrom, request.A12ValidTo) : null)
                ?? (has80G ? CheckValidity("80G", request.EightyGValidFrom, request.EightyGValidTo) : null)
                ?? (hasFcra ? CheckValidity("FCRA", request.FcraValidFrom, request.FcraValidTo) : null);
            if (badPeriod != null)
            {
                return Fail(badPeriod);
            }

            // TAN list: blank rows ignored; each TAN valid, not in the future, not repeated.
            List<MasterInstiTan> tans = new List<MasterInstiTan>();
            IEnumerable<LegalEntityTanDto> requestedTans = request.Tans ?? new List<LegalEntityTanDto>();
            foreach (LegalEntityTanDto tan in requestedTans)
            {
                string number = Clean(tan.TanNo).ToUpperInvariant();
                string name = Clean(tan.TanName);
                if (number.Length == 0 && name.Length == 0 && !tan.TanRegDate.HasValue)
                {
                    continue;
                }

                if (number.Length == 0)
                {
                    return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_TAN_NO_EMPTY));
                }

                if (!TanPattern.IsMatch(number))
                {
                    return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_TAN_INVALID, number));
                }

                if (tans.Any(item => item.TanNo == number))
                {
                    return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_TAN_DUPLICATE, number));
                }

                string? tanProblem = CheckNotFuture("TAN Register Date", tan.TanRegDate, today) ?? CheckLength("TAN Name", name, 100);
                if (tanProblem != null)
                {
                    return Fail(tanProblem);
                }

                tans.Add(new MasterInstiTan { TanNo = number, TanRegDate = WriteDate(tan.TanRegDate), TanName = name });
            }

            string contactPerson = Clean(request.ContactPerson);
            string address = Clean(request.Address);
            string place = Clean(request.Place);
            string pincode = Clean(request.Pincode);
            string phone = Clean(request.Phone);
            string fax = Clean(request.Fax);
            string url = Clean(request.Url);
            string permissionNo = Clean(request.PermissionNo);
            string girNo = Clean(request.GirNo);
            // TANNO keeps the first TAN for older readers of MASTER_INSTI_PERFERENCE.
            string tanNo = tans.Count > 0 ? tans[0].TanNo : string.Empty;
            string darpanName = hasDarpan ? Clean(request.DarpanName) : string.Empty;
            string a12Name = has12A ? Clean(request.A12Name) : string.Empty;
            string eightyGName = has80G ? Clean(request.EightyGName) : string.Empty;
            string principalActivity = Clean(request.PrincipalActivity);
            string associationNature = string.Join(",", natures);

            string? tooLong = CheckLength("Society Name", societyName, 100)
                ?? CheckLength("Contact Person", contactPerson, 100)
                ?? CheckLength("Address", address, 500)
                ?? CheckLength("Place", place, 100)
                ?? CheckLength("State/Province", state, 100)
                ?? CheckLength("Country", country, 100)
                ?? CheckLength("Pincode", pincode, 20)
                ?? CheckLength("Phone", phone, 20)
                ?? CheckLength("Fax", fax, 20)
                ?? CheckLength("Email", email, 100)
                ?? CheckLength("URL", url, 100)
                ?? CheckLength("Society/Reg.No", regNo, 100)
                ?? CheckLength("Prior Permission No", permissionNo, 50)
                ?? CheckLength("12A No", a12No, 100)
                ?? CheckLength("PAN No", panNo, 10)
                ?? CheckLength("GIR No", girNo, 50)
                ?? CheckLength("TAN No", tanNo, 10)
                ?? CheckLength("FCRA No", fcriNo, 30)
                ?? CheckLength("80G.No", eightyGNo, 20)
                ?? CheckLength("Association Nature Others", otherAssociation, 100)
                ?? CheckLength("Denomination Others", otherDenomination, 100)
                ?? CheckLength("Principal Activity", principalActivity, 100)
                ?? CheckLength("Trust Doc Number", trustDocNo, 100)
                ?? CheckLength("Branch and Users In-charge", branchIncharge, 100)
                ?? CheckLength("PAN Name", panName, 100)
                ?? CheckLength("DARPAN ID", darpanId, 30)
                ?? CheckLength("DARPAN Name", darpanName, 100)
                ?? CheckLength("12A Name", a12Name, 100)
                ?? CheckLength("80G Name", eightyGName, 100);
            if (tooLong != null)
            {
                return Fail(tooLong);
            }

            try
            {
                await using (MastersDbContext tenant = await OpenTenantAsync(office, cancellationToken))
                {
                    // SOCIETYNAME has a unique index (master_insti_perference_unique_societyname).
                    string lower = societyName.ToLowerInvariant();
                    bool duplicate = await tenant.Set<MasterInstiPerference>().AnyAsync(
                        row => (row.SocietyName ?? string.Empty).ToLower() == lower
                            && row.CustomerId != request.CustomerId,
                        cancellationToken);
                    if (duplicate)
                    {
                        return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_EXISTS));
                    }

                    MasterInstiPerference? target;
                    if (request.CustomerId <= 0)
                    {
                        target = new MasterInstiPerference();
                        tenant.Set<MasterInstiPerference>().Add(target);
                    }
                    else
                    {
                        target = await tenant.Set<MasterInstiPerference>().FirstOrDefaultAsync(
                            row => row.CustomerId == request.CustomerId, cancellationToken);
                        if (target == null)
                        {
                            return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_NOT_FOUND));
                        }
                    }

                    target.SocietyName = societyName;
                    target.ContactPerson = contactPerson;
                    target.Address = address;
                    target.Place = place;
                    target.State = state;
                    target.Country = country;
                    target.Pincode = pincode;
                    target.Phone = phone;
                    target.Fax = fax;
                    target.Email = email;
                    target.Url = url;
                    target.RegNo = regNo;
                    target.RegDate = WriteDate(request.RegDate);
                    target.PermissionNo = permissionNo;
                    target.PermissionDate = WriteDate(request.PermissionDate);
                    target.A12No = a12No;
                    target.PanNo = panNo;
                    target.GirNo = girNo;
                    target.TanNo = tanNo;
                    target.FcriNo = fcriNo;
                    target.FcriRegDate = hasFcra ? WriteDate(request.FcriRegDate) : null;
                    target.EightyGNo = eightyGNo;
                    target.EightyGNoRegDate = has80G ? WriteDate(request.EightyGNoRegDate) : null;
                    target.AssociationNature = associationNature;
                    target.OtherAssociationNature = otherAssociation;
                    target.Denomination = denomination;
                    target.OtherDenomination = otherDenomination;
                    target.IsFoundation = request.IsFoundation ? 1 : 0;
                    target.PrincipalActivity = principalActivity;

                    // Main row first (a new legal entity gets its CUSTOMERID), then its statutory row and TANs,
                    // all in one transaction.
                    await using (var transaction = await tenant.Database.BeginTransactionAsync(cancellationToken))
                    {
                        await tenant.SaveChangesAsync(cancellationToken);

                        MasterInstiStatutory? statutory = await tenant.Set<MasterInstiStatutory>().FirstOrDefaultAsync(
                            row => row.CustomerId == target.CustomerId, cancellationToken);
                        if (statutory == null)
                        {
                            statutory = new MasterInstiStatutory { CustomerId = target.CustomerId };
                            tenant.Set<MasterInstiStatutory>().Add(statutory);
                        }

                        statutory.EntityType = request.EntityType;
                        statutory.TrustDocNo = trustDocNo;
                        statutory.BranchIncharge = branchIncharge;
                        statutory.PanStatus = request.PanStatus;
                        statutory.PanName = panName;
                        statutory.PanRegDate = hasPan ? WriteDate(request.PanRegDate) : null;
                        statutory.DarpanStatus = request.DarpanStatus;
                        statutory.DarpanId = darpanId;
                        statutory.DarpanRegDate = hasDarpan ? WriteDate(request.DarpanRegDate) : null;
                        statutory.DarpanName = darpanName;
                        statutory.A12Status = request.A12Status;
                        statutory.A12ValidFrom = has12A ? WriteDate(request.A12ValidFrom) : null;
                        statutory.A12ValidTo = has12A ? WriteDate(request.A12ValidTo) : null;
                        statutory.A12Name = a12Name;
                        statutory.EightyGStatus = request.EightyGStatus;
                        statutory.EightyGValidFrom = has80G ? WriteDate(request.EightyGValidFrom) : null;
                        statutory.EightyGValidTo = has80G ? WriteDate(request.EightyGValidTo) : null;
                        statutory.EightyGName = eightyGName;
                        statutory.FcraStatus = request.FcraStatus;
                        statutory.FcraValidFrom = hasFcra ? WriteDate(request.FcraValidFrom) : null;
                        statutory.FcraValidTo = hasFcra ? WriteDate(request.FcraValidTo) : null;

                        // Replace the TAN list.
                        List<MasterInstiTan> oldTans = await tenant.Set<MasterInstiTan>()
                            .Where(row => row.CustomerId == target.CustomerId)
                            .ToListAsync(cancellationToken);
                        tenant.Set<MasterInstiTan>().RemoveRange(oldTans);
                        await tenant.SaveChangesAsync(cancellationToken);
                        foreach (MasterInstiTan tan in tans)
                        {
                            tan.CustomerId = target.CustomerId;
                            tenant.Set<MasterInstiTan>().Add(tan);
                        }

                        await tenant.SaveChangesAsync(cancellationToken);
                        await transaction.CommitAsync(cancellationToken);
                    }

                    return Ok(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_SAVE_SUCCESS), target.CustomerId);
                }
            }
            catch (Exception ex)
            {
                return Fail(ex.Message);
            }
        }

        /// <summary>
        /// A legal entity linked to projects (MASTER_PROJECT.CUSTOMERID, FK) or mapped to governing bodies
        /// (EXECUTIVE_LEGAL_ENTITY) cannot be deleted.
        /// </summary>
        public async Task<LegalEntityActionResult> DeleteLegalEntityDetails(HeadOfficeConnection office, int customerId, CancellationToken cancellationToken)
        {
            if (customerId <= 0)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_NOT_FOUND));
            }

            try
            {
                await using (MastersDbContext tenant = await OpenTenantAsync(office, cancellationToken))
                {
                    MasterInstiPerference? existing = await tenant.Set<MasterInstiPerference>().FirstOrDefaultAsync(
                        row => row.CustomerId == customerId, cancellationToken);
                    if (existing == null)
                    {
                        return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_NOT_FOUND));
                    }

                    bool usedByProject = await tenant.Set<MasterProject>().AsNoTracking()
                        .AnyAsync(row => row.CustomerId == customerId, cancellationToken);
                    if (usedByProject)
                    {
                        return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_USED_BY_PROJECT));
                    }

                    bool mapped = await tenant.Set<ExecutiveLegalEntity>().AsNoTracking()
                        .AnyAsync(row => row.CustomerId == customerId, cancellationToken);
                    if (mapped)
                    {
                        return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_MAPPED_TO_GOVERNING_BODY));
                    }

                    tenant.Set<MasterInstiPerference>().Remove(existing);
                    await tenant.SaveChangesAsync(cancellationToken);
                    return Ok(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_DELETE_SUCCESS), customerId);
                }
            }
            catch (Exception)
            {
                return Fail(MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_DELETE_FAILURE));
            }
        }

        private static string Clean(string? value)
        {
            return (value ?? string.Empty).Trim();
        }

        private static string? CheckLength(string caption, string value, int max)
        {
            if (value.Length <= max)
            {
                return null;
            }

            return MessageRender.GetMessage(GoverningLegalMessages.STATUTORY_FIELD_MAX, caption, max);
        }

        // Status codes: null (not chosen), 1 Registered, 0 Not Registered.
        private static string? CheckStatus(string caption, int? status)
        {
            if (!status.HasValue || status.Value == StatusYes || status.Value == StatusNo)
            {
                return null;
            }

            return MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_STATUS_INVALID, caption);
        }

        private static string NumberRequired(string caption)
        {
            return MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_STATUS_NUMBER_EMPTY, caption);
        }

        private static string? CheckNotFuture(string caption, DateTime? value, DateTime today)
        {
            if (!value.HasValue || value.Value.Date <= today)
            {
                return null;
            }

            return MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_DATE_FUTURE, caption);
        }

        // Validity period: both dates together, To after From.
        private static string? CheckValidity(string caption, DateTime? from, DateTime? to)
        {
            if (!from.HasValue && !to.HasValue)
            {
                return null;
            }

            if (!from.HasValue || !to.HasValue)
            {
                return MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_VALIDITY_INCOMPLETE, caption);
            }

            if (to.Value.Date < from.Value.Date)
            {
                return MessageRender.GetMessage(GoverningLegalMessages.LEGAL_ENTITY_VALIDITY_ORDER, caption);
            }

            return null;
        }

        /// <summary>
        /// "0,3,5" -> distinct valid association nature ids (0..5) in ascending order, as the legacy page stored them.
        /// </summary>
        private static List<int> ParseAssociationNature(string? value)
        {
            List<int> natures = new List<int>();
            string[] parts = (value ?? string.Empty).Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
            for (int i = 0; i < parts.Length; i++)
            {
                int nature;
                if (int.TryParse(parts[i], out nature) && nature >= 0 && nature <= AssociationMax && !natures.Contains(nature))
                {
                    natures.Add(nature);
                }
            }

            natures.Sort();
            return natures;
        }

        // Tenant date columns are timestamp without time zone; EF maps DateTime as timestamptz, so write UTC-kind dates.
        private static DateTime? WriteDate(DateTime? value)
        {
            return value.HasValue ? DateTime.SpecifyKind(value.Value.Date, DateTimeKind.Utc) : null;
        }

        private static DateTime? ReadDate(DateTime? value)
        {
            return value.HasValue ? value.Value.Date : null;
        }
